using System.Globalization;
using System.IO;
using Newtonsoft.Json;
using Serilog;
using UndertaleModLib;
using UndertaleModLib.Decompiler;
using UndertaleModLib.Models;

namespace ModShardLauncher;

/// <summary>
/// Optional per-data-file cache of the decompiler's authoring state.
/// <para>
/// A patch run pays two one-off costs that have nothing to do with the mods: the decompiler
/// recursively decompiles every script it can reach just to type the arguments of the functions it
/// calls (<see cref="GlobalDecompileContext.ScriptArgsCache"/>,
/// <see cref="GlobalDecompileContext.AnonymousFunctionNameCache"/>), and
/// <see cref="Decompiler.BuildSubFunctionCache"/> decompiles all 3280 global init scripts to map
/// <c>Foo = function() {...}</c> assignments to their function objects.
/// </para>
/// <para>
/// Both are pure functions of the data file, so they are stored next to the user data and replayed.
/// The replay is deliberately conservative:
/// </para>
/// <list type="bullet">
/// <item>the cache is keyed by the data file's MD5 plus the MSL and UndertaleModLib versions;</item>
/// <item>the sub-function table is only replaced when every entry resolves to exactly one function,
/// otherwise the library rebuilds it (slow but always correct);</item>
/// <item><c>Autogenerated</c> is <b>not</b> stored: it is re-derived from the code names, which is
/// what <see cref="Decompiler.BuildSubFunctionCache"/> does (it only decides function binding, see
/// <c>AssemblyWriter</c>, and never reaches the output file);</item>
/// <item>the script signatures are only replayed for names that still exist in the script table;</item>
/// <item><c>MSL_NO_DECOMPILER_CACHE=1</c> disables everything, and a missing or unreadable cache
/// falls back to the library's own analysis.</item>
/// </list>
/// <para>
/// <see cref="Learn"/> merges this run's state into the stored one, so a run with fewer mods can only
/// add entries.
/// </para>
/// </summary>
internal static class DecompilerCacheStore
{
    /// <summary>Bump when the stored shape or the replay rules change.</summary>
    internal const int Schema = 2;

    internal const string DisableVariable = "MSL_NO_DECOMPILER_CACHE";
    internal const string DirectoryVariable = "MSL_CACHE_DIR";

    private const string ScriptPrefix = "gml_Script_";

    private static readonly object Gate = new();

    private static string? _checksum;
    private static string? _loggedChecksum;
    private static bool _applied;
    private static CachePayload? _appliedPayload;

    /// <summary>Whether the currently loaded data file was restored from a cache.</summary>
    internal static bool WasApplied
    {
        get
        {
            lock (Gate)
            {
                return _applied;
            }
        }
    }

    /// <summary>A short description of the applied cache, for the log.</summary>
    internal static string Describe()
    {
        lock (Gate)
        {
            if (!_applied || _appliedPayload is null)
            {
                return "not used";
            }

            return string.Create(
                CultureInfo.InvariantCulture,
                $"sub-functions {_appliedPayload.SubFunctionExtras?.Count ?? 0}, " +
                $"script signatures {_appliedPayload.ScriptArgs?.Count ?? 0}, " +
                $"anonymous names {_appliedPayload.AnonymousFunctionNames?.Count ?? 0}");
        }
    }

    internal static void Reset()
    {
        lock (Gate)
        {
            _checksum = null;
            _applied = false;
            _appliedPayload = null;
        }
    }

    private static bool IsDisabled() =>
        string.Equals(Environment.GetEnvironmentVariable(DisableVariable), "1", StringComparison.OrdinalIgnoreCase);

    /// <summary>Where the cache for one data file lives; <c>MSL_CACHE_DIR</c> overrides it (tests).</summary>
    internal static string PathFor(string checksum)
    {
        string directory = Environment.GetEnvironmentVariable(DirectoryVariable) is { Length: > 0 } overridden
            ? overridden
            : AppPaths.CacheDirectory;
        return Path.Combine(directory, $"decompiler-{checksum}.json");
    }

    /// <summary>
    /// Restores the decompiler state for <paramref name="data"/> if a matching cache exists.
    /// Returns false (and leaves the data untouched) when there is nothing usable.
    /// </summary>
    internal static bool TryApply(string? checksum, UndertaleData data, GlobalDecompileContext context)
    {
        if (string.IsNullOrEmpty(checksum) || IsDisabled())
        {
            Reset();
            return false;
        }

        lock (Gate)
        {
            _checksum = checksum;
            _applied = false;
            _appliedPayload = null;
        }

        CachePayload? payload = Read(checksum);
        if (payload is null)
        {
            return false;
        }

        if (!TryBuildSubFunctions(payload, data, out Dictionary<string, UndertaleFunction>? subFunctions))
        {
            return false;
        }

        Dictionary<string, UndertaleFunction> uniqueFunctions = BuildUniqueFunctionIndex(data, out HashSet<string> ambiguous);

        if (payload.ScriptArgs is { Count: > 0 })
        {
            HashSet<string> scriptNames = new(data.Scripts.Count, StringComparer.Ordinal);
            foreach (UndertaleScript script in data.Scripts)
            {
                if (script.Name?.Content is string name)
                {
                    scriptNames.Add(name);
                }
            }

            foreach ((string name, int[]? types) in payload.ScriptArgs)
            {
                if (!scriptNames.Contains(name))
                {
                    continue;
                }

                context.ScriptArgsCache[name] = types is null
                    ? null!
                    : Array.ConvertAll(types, x => (AssetIDType)x);
            }
        }

        if (payload.AnonymousFunctionNames is { Count: > 0 })
        {
            foreach ((string functionName, string resolvedName) in payload.AnonymousFunctionNames)
            {
                if (resolvedName is null || ambiguous.Contains(functionName))
                {
                    continue;
                }

                if (uniqueFunctions.TryGetValue(functionName, out UndertaleFunction? function))
                {
                    context.AnonymousFunctionNameCache[function] = resolvedName;
                }
            }
        }

        // Only replace the table once everything above succeeded: a partial table changes the
        // decompiled text and the compiled function bindings (see the class remarks).
        if (subFunctions is not null)
        {
            data.KnownSubFunctions = subFunctions;
            ApplyAutogenerated(data);
        }

        lock (Gate)
        {
            _applied = true;
            _appliedPayload = payload;
        }

        if (_loggedChecksum != checksum)
        {
            _loggedChecksum = checksum;
            Log.Information("Decompiler cache hit for {File}: {Detail}",
                Path.GetFileName(PathFor(checksum)), Describe());
        }

        return true;
    }

    /// <summary>
    /// Merges the current run's decompiler state into the persisted cache. Never throws: a cache
    /// problem must not fail a patch.
    /// </summary>
    internal static void Learn(UndertaleData? data)
    {
        try
        {
            if (data is null || !MslContext.HasData || IsDisabled())
            {
                return;
            }

            string? checksum;
            lock (Gate)
            {
                checksum = _checksum;
            }

            if (string.IsNullOrEmpty(checksum) || data.KnownSubFunctions is null)
            {
                return;
            }

            GlobalDecompileContext context = MslContext.DecompilerCache;
            CachePayload merged = Merge(Read(checksum), Build(checksum, data, context));
            Write(checksum, merged);
        }
        catch (Exception ex)
        {
            Log.Debug(ex, "Cannot persist the decompiler cache");
        }
    }

    private static CachePayload Build(string checksum, UndertaleData data, GlobalDecompileContext context)
    {
        CachePayload payload = new()
        {
            Schema = Schema,
            DataChecksum = checksum,
            MslVersion = AppInfo.MslVersion,
            UtmtLibVersion = AppInfo.UtmtLibVersion,
        };

        // Entries the "gml_Script_<name>" prefix rule cannot explain. Compiler-created sub-functions
        // always follow that rule (AssemblyWriter names them "gml_Script_" + key), so a run with more
        // or fewer mods cannot leak its own additions in here.
        payload.SubFunctionExtras = new List<SubFunctionEntry>();
        foreach ((string key, UndertaleFunction value) in data.KnownSubFunctions)
        {
            string? functionName = value?.Name?.Content;
            if (functionName is null)
            {
                continue;
            }

            if (functionName != ScriptPrefix + key)
            {
                payload.SubFunctionExtras.Add(new SubFunctionEntry { Key = key, Function = functionName });
            }
        }

        payload.ScriptArgs = new Dictionary<string, int[]?>(StringComparer.Ordinal);
        foreach ((string name, AssetIDType[]? types) in context.ScriptArgsCache)
        {
            payload.ScriptArgs[name] = types is null ? null : Array.ConvertAll(types, x => (int)x);
        }

        payload.AnonymousFunctionNames = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach ((UndertaleFunction function, string resolvedName) in context.AnonymousFunctionNameCache)
        {
            string? functionName = function?.Name?.Content;
            if (functionName is not null && resolvedName is not null)
            {
                payload.AnonymousFunctionNames[functionName] = resolvedName;
            }
        }

        return payload;
    }

    /// <summary>
    /// Union of the stored and the new payload. A key observed by both keeps the value from the run
    /// that just finished; the stored payload only fills the gaps. Merging means a run with fewer
    /// mods can only add entries, never shrink the cache.
    /// </summary>
    private static CachePayload Merge(CachePayload? stored, CachePayload current)
    {
        if (stored is null)
        {
            return current;
        }

        current.SubFunctionExtras ??= new List<SubFunctionEntry>();
        Dictionary<string, SubFunctionEntry> extras = new(StringComparer.Ordinal);
        foreach (SubFunctionEntry entry in current.SubFunctionExtras)
        {
            if (entry.Key is not null)
            {
                extras.TryAdd(entry.Key, entry);
            }
        }

        foreach (SubFunctionEntry entry in stored.SubFunctionExtras ?? [])
        {
            if (entry.Key is not null)
            {
                extras.TryAdd(entry.Key, entry);
            }
        }

        current.SubFunctionExtras = extras.Values.OrderBy(x => x.Key, StringComparer.Ordinal).ToList();

        current.ScriptArgs ??= new Dictionary<string, int[]?>(StringComparer.Ordinal);
        foreach ((string name, int[]? types) in stored.ScriptArgs ?? [])
        {
            current.ScriptArgs.TryAdd(name, types);
        }

        current.AnonymousFunctionNames ??= new Dictionary<string, string>(StringComparer.Ordinal);
        foreach ((string name, string resolved) in stored.AnonymousFunctionNames ?? [])
        {
            current.AnonymousFunctionNames.TryAdd(name, resolved);
        }

        return current;
    }

    /// <summary>
    /// Rebuilds <c>KnownSubFunctions</c>: the cheap <c>gml_Script_*</c> half (the vast majority) plus
    /// the stored extras. Returns false when the stored data cannot be reproduced exactly, in which
    /// case the caller must let the library build the table itself.
    /// </summary>
    private static bool TryBuildSubFunctions(
        CachePayload payload,
        UndertaleData data,
        out Dictionary<string, UndertaleFunction>? table)
    {
        table = null;
        if (payload.SubFunctionExtras is null)
        {
            return true; // nothing stored about sub-functions: leave the table alone
        }

        Dictionary<string, UndertaleFunction> built = new(StringComparer.Ordinal);
        foreach (UndertaleFunction function in data.Functions)
        {
            string? name = function.Name?.Content;
            if (name is not null && name.StartsWith(ScriptPrefix, StringComparison.Ordinal))
            {
                built.TryAdd(name[ScriptPrefix.Length..], function);
            }
        }

        if (payload.SubFunctionExtras.Count > 0)
        {
            Dictionary<string, UndertaleFunction> unique = BuildUniqueFunctionIndex(data, out _);
            foreach (SubFunctionEntry entry in payload.SubFunctionExtras)
            {
                if (entry.Key is null || entry.Function is null)
                {
                    return false;
                }

                if (!unique.TryGetValue(entry.Function, out UndertaleFunction? function))
                {
                    // The function is gone (or the name is ambiguous): rebuild from scratch.
                    return false;
                }

                built.TryAdd(entry.Key, function);
            }
        }

        table = built;
        return true;
    }

    /// <summary>Name to function map; names used more than once are reported in <paramref name="ambiguous"/>.</summary>
    private static Dictionary<string, UndertaleFunction> BuildUniqueFunctionIndex(
        UndertaleData data,
        out HashSet<string> ambiguous)
    {
        Dictionary<string, UndertaleFunction> index = new(StringComparer.Ordinal);
        ambiguous = new HashSet<string>(StringComparer.Ordinal);

        foreach (UndertaleFunction function in data.Functions)
        {
            string? name = function.Name?.Content;
            if (name is null)
            {
                continue;
            }

            if (!index.TryAdd(name, function))
            {
                ambiguous.Add(name);
            }
        }

        return index;
    }

    /// <summary>
    /// Recreates the flag <see cref="Decompiler.BuildSubFunctionCache"/> sets (and that the GML
    /// compiler reads to decide whether a FUNC entry may be called directly).
    /// </summary>
    private static void ApplyAutogenerated(UndertaleData data)
    {
        HashSet<string> codeNames = new(data.Code.Count, StringComparer.Ordinal);
        foreach (UndertaleCode code in data.Code)
        {
            if (code.Name?.Content is string name)
            {
                codeNames.Add(name);
            }
        }

        foreach (UndertaleFunction function in data.Functions)
        {
            if (function.Name?.Content is string name && codeNames.Contains(name))
            {
                function.Autogenerated = true;
            }
        }
    }

    private static CachePayload? Read(string checksum)
    {
        if (IsDisabled())
        {
            return null;
        }

        string path = PathFor(checksum);
        try
        {
            if (!File.Exists(path))
            {
                return null;
            }

            CachePayload? payload = JsonConvert.DeserializeObject<CachePayload>(File.ReadAllText(path));
            if (payload is null ||
                payload.Schema != Schema ||
                payload.DataChecksum != checksum ||
                payload.MslVersion != AppInfo.MslVersion ||
                payload.UtmtLibVersion != AppInfo.UtmtLibVersion)
            {
                Log.Debug("Ignoring stale decompiler cache {Path}", path);
                return null;
            }

            return payload;
        }
        catch (Exception ex)
        {
            Log.Debug(ex, "Cannot read the decompiler cache {Path}", path);
            return null;
        }
    }

    private static void Write(string checksum, CachePayload payload)
    {
        string path = PathFor(checksum);
        try
        {
            string? directory = Path.GetDirectoryName(path);
            if (directory is not null)
            {
                Directory.CreateDirectory(directory);
            }

            File.WriteAllText(path, JsonConvert.SerializeObject(payload));
            Log.Debug("Decompiler cache written to {Path}", path);
        }
        catch (Exception ex)
        {
            Log.Debug(ex, "Cannot write the decompiler cache {Path}", path);
        }
    }

    private sealed class CachePayload
    {
        [JsonProperty("schema")]
        public int Schema { get; set; }

        [JsonProperty("dataChecksum")]
        public string? DataChecksum { get; set; }

        [JsonProperty("mslVersion")]
        public string? MslVersion { get; set; }

        [JsonProperty("utmtLibVersion")]
        public string? UtmtLibVersion { get; set; }

        [JsonProperty("subFunctionExtras", NullValueHandling = NullValueHandling.Ignore)]
        public List<SubFunctionEntry>? SubFunctionExtras { get; set; }

        [JsonProperty("scriptArgs", NullValueHandling = NullValueHandling.Ignore)]
        public Dictionary<string, int[]?>? ScriptArgs { get; set; }

        [JsonProperty("anonymousFunctionNames", NullValueHandling = NullValueHandling.Ignore)]
        public Dictionary<string, string>? AnonymousFunctionNames { get; set; }
    }

    private sealed class SubFunctionEntry
    {
        [JsonProperty("key")]
        public string? Key { get; set; }

        [JsonProperty("function")]
        public string? Function { get; set; }
    }
}
