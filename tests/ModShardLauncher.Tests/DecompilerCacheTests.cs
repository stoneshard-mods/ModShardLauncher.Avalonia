using ModShardLauncher;
using UndertaleModLib;
using UndertaleModLib.Decompiler;
using UndertaleModLib.Models;
using Xunit.Abstractions;

namespace ModShardLauncherTest;

/// <summary>
/// The decompiler cache is the biggest performance lever of the patch pipeline, and it is only safe
/// if the replayed state is <b>exactly</b> what the library would compute: a single missing
/// sub-function changes the decompiled text and the compiled function bindings.
/// These tests pin the replay fidelity and every fallback.
/// </summary>
[Collection(GameDataCollection.Name)]
public class DecompilerCacheTests
{
    private readonly ITestOutputHelper _output;

    public DecompilerCacheTests(ITestOutputHelper output) => _output = output;

    /// <summary>Builds the table with the library, persists it, reloads and compares.</summary>
    [Fact]
    public async Task ReplayedState_MatchesTheLibraryBuild()
    {
        string? dataPath = TryGetDataPath();
        if (dataPath is null)
        {
            return;
        }

        DeleteCacheFor(dataPath);

        GameDataService first = new();
        await first.LoadAsync(dataPath);
        PatchBaselineSupport.AssertVanilla(dataPath);
        Assert.False(DecompilerCacheStore.WasApplied, "the cache was just deleted, nothing to replay");

        // What the patch pipeline would pay for on its first run.
        Decompiler.BuildSubFunctionCache(MslContext.Data);
        Dictionary<string, string> built = SnapshotTable(MslContext.Data);
        HashSet<string> builtFlags = SnapshotAutogenerated(MslContext.Data);
        _output.WriteLine($"library build: {built.Count} sub-functions, {builtFlags.Count} autogenerated flags");

        DecompilerCacheStore.Learn(MslContext.Data);
        Assert.True(File.Exists(DecompilerCacheStore.PathFor(ChecksumOf(dataPath))), "the run must persist its state");

        // Reload: the table must now come from the cache instead of the table being rebuilt.
        GameDataService second = new();
        await second.LoadAsync(dataPath);
        Assert.True(DecompilerCacheStore.WasApplied, "the cache written by the previous load must be replayed");
        Assert.NotNull(MslContext.Data.KnownSubFunctions);

        Assert.Equal(built, SnapshotTable(MslContext.Data));
        Assert.Equal(builtFlags, SnapshotAutogenerated(MslContext.Data));
        _output.WriteLine($"replayed    : {MslContext.Data.KnownSubFunctions!.Count} sub-functions");
    }

    [Fact]
    public async Task UnreadableCache_FallsBackToTheLibraryBuild()
    {
        string? dataPath = TryGetDataPath();
        if (dataPath is null)
        {
            return;
        }

        string path = DecompilerCacheStore.PathFor(ChecksumOf(dataPath));
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, "{ this is not json");

        GameDataService service = new();
        await service.LoadAsync(dataPath);

        Assert.False(DecompilerCacheStore.WasApplied);
        Assert.Null(MslContext.Data.KnownSubFunctions);
    }

    [Fact]
    public async Task CacheFromAnotherVersion_IsIgnored()
    {
        string? dataPath = TryGetDataPath();
        if (dataPath is null)
        {
            return;
        }

        string path = DecompilerCacheStore.PathFor(ChecksumOf(dataPath));
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, """
            { "schema": 0, "dataChecksum": "deadbeef", "mslVersion": "v0.0.0.0",
              "utmtLibVersion": "v0.0.0.0", "subFunctionExtras": [], "scriptArgs": {} }
            """);

        GameDataService service = new();
        await service.LoadAsync(dataPath);

        Assert.False(DecompilerCacheStore.WasApplied);
        Assert.Null(MslContext.Data.KnownSubFunctions);
    }

    [Fact]
    public async Task DisabledByEnvironment_NeitherReadsNorWrites()
    {
        string? dataPath = TryGetDataPath();
        if (dataPath is null)
        {
            return;
        }

        DeleteCacheFor(dataPath);
        Environment.SetEnvironmentVariable(DecompilerCacheStore.DisableVariable, "1");
        try
        {
            GameDataService service = new();
            await service.LoadAsync(dataPath);
            Assert.False(DecompilerCacheStore.WasApplied);

            Decompiler.BuildSubFunctionCache(MslContext.Data);
            DecompilerCacheStore.Learn(MslContext.Data);
            Assert.False(File.Exists(DecompilerCacheStore.PathFor(ChecksumOf(dataPath))),
                "a disabled cache must not be written");
        }
        finally
        {
            Environment.SetEnvironmentVariable(DecompilerCacheStore.DisableVariable, null);
        }
    }

    // ----- helpers ------------------------------------------------------------------------------

    private string? TryGetDataPath()
    {
        string? path = PatchBaselineSupport.TryGetDataPath();
        if (path is null)
        {
            _output.WriteLine(PatchBaselineSupport.MissingDataMessage);
        }

        return path;
    }

    private static string ChecksumOf(string dataPath)
    {
        using FileStream stream = new(dataPath, FileMode.Open, FileAccess.Read);
        return DataChecksumValidator.ComputeChecksum(stream);
    }

    private static void DeleteCacheFor(string dataPath)
    {
        string path = DecompilerCacheStore.PathFor(ChecksumOf(dataPath));
        if (File.Exists(path))
        {
            File.Delete(path);
        }
    }

    private static Dictionary<string, string> SnapshotTable(UndertaleData data)
    {
        Dictionary<string, string> snapshot = new(StringComparer.Ordinal);
        foreach ((string key, UndertaleFunction value) in data.KnownSubFunctions!)
        {
            snapshot[key] = value?.Name?.Content ?? "<null>";
        }

        return snapshot;
    }

    private static HashSet<string> SnapshotAutogenerated(UndertaleData data) =>
        new(data.Functions.Where(f => f.Autogenerated).Select(f => f.Name!.Content), StringComparer.Ordinal);
}
